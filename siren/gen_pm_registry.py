import glob, os, re, subprocess, sys
sys.path.insert(0, 'D:/consoles/ps3/ps3recomp/tools')
from wrap_spu_elf import wrap

spu_dir = 'D:/consoles/ps3/siren/spu'
dump_dir = 'D:/consoles/ps3/siren/spudump'
lifter = 'D:/consoles/ps3/ps3recomp/tools/spu_lifter.py'

bins = sorted(glob.glob(os.path.join(dump_dir, 'spujob_*.bin')))
assert len(bins) == 13, f'expected 13 spujob bins, got {len(bins)}'

entries = []
for bpath in bins:
    m = re.match(r'spujob_([0-9A-Fa-f]+)_\d+\.bin$', os.path.basename(bpath))
    assert m, bpath
    fp = m.group(1).upper()
    out_d = os.path.join(spu_dir, f'pm_{fp}')
    os.makedirs(out_d, exist_ok=True)
    raw = open(bpath, 'rb').read()
    is_wws = (fp == '416BED66783749FF')
    base = 0xA00 if is_wws else 0x0
    elf_path = os.path.join(out_d, 'wrapped.elf')
    with open(elf_path, 'wb') as f:
        f.write(wrap(raw, base=base, entry=base))
    cmd = [
        sys.executable, lifter,
        '--auto-functions', elf_path,
        '--base', hex(base),
        '--return-entries',
        '--merge-chunks',
        '--symbol-prefix', f'pm_{fp}_',
        '--output', out_d,
    ]
    if is_wws:
        cmd += ['--extra-funcs', '0xA2C', '--force-indirect', '0x277C']
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise RuntimeError(f'lift failed for {fp}: {p.stderr}')
    hdr = os.path.join(out_d, 'spu_recomp.h')
    txt = open(hdr, encoding='utf-8', errors='ignore').read()
    ext_cnt = txt.count('/* external */')
    entry_sym = f'pm_{fp}_spu_func_{base:08X}'
    assert entry_sym + '(' in txt, f'missing {entry_sym} in {hdr}'
    reg_sym = f'pm_{fp}_spu_recomp_register'
    assert reg_sym + '(' in txt, f'missing {reg_sym} in {hdr}'
    print(f'pm_{fp}: base=0x{base:X} entry={entry_sym} externals={ext_cnt}')
    entries.append((fp, entry_sym, reg_sym))

L = []
L.append('/* siren_spu_workloads.c -- GENERATED by gen_pm_registry.py.')
L.append(' * Registers hand-lifted raw SPU PMs (from SPU_DUMP_MISS) by FNV-1a-64,')
L.append(' * plus the 13 engine-embedded WWS job modules (image ids 200..212). */')
L.append('#include "spu_workload.h"')
L.append('')
L.append('extern void spu_begin_image(int image_id);')
L.append('')
# jobmods_register.c has its own constructor; no explicit call needed.
for fp, entry, reg in entries:
    L.append('extern void ' + entry + '(spu_context*);')
    L.append('extern void ' + reg + '(void);')
L.append('')
L.append('static void siren_spu_register_all(void)')
L.append('{')
for i, (fp, entry, reg) in enumerate(entries):
    imgid = 3001 + i
    L.append('    spu_begin_image(%d); %s();' % (imgid, reg))
    L.append('    spu_workload_register_img(0x%sULL, %s, %d, "pm_%s");' % (fp, entry, imgid, fp))
L.append('    spu_begin_image(0);')
L.append('}')
L.append('')
L.append('#if defined(_MSC_VER) || defined(__clang__)')
L.append('__attribute__((constructor)) static void siren_spu_register_ctor(void) { siren_spu_register_all(); }')
L.append('#endif')
L.append('')
open(os.path.join(spu_dir, 'siren_spu_workloads.c'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
print('wrote registry for %d images (jobmods self-register via ctor)' % len(entries))
